#!/usr/bin/env bash
# Regenerate the per-header independence translation units and report drift.
#
# Roadmap task A02a: "Compile every advertised public header as the first and
# only library header in its own translation unit." The units are checked in so
# that an ordinary build enforces it; this script is what keeps the set honest
# when a header is added, removed or moved between the dependency-free and Qt
# halves of the surface.
#
# It also reports, rather than assumes, which half each header belongs to. A
# header that starts needing Qt is a design change, not a classification to be
# adjusted quietly.
set -euo pipefail

root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
inc="$root/libs/collabtext/include/collabtext"
out="$root/libs/collabtext/tests/public-headers"

deps() {  # transitive collabtext/ includes of one header
    python3 - "$1" "$inc" <<'PY'
import re, sys, pathlib
name, inc = sys.argv[1], pathlib.Path(sys.argv[2])
seen, stack, out = set(), [name], set()
while stack:
        cur = stack.pop()
        if cur in seen: continue
        seen.add(cur)
        p = inc/cur
        if not p.exists(): continue
        out.add(cur)
        for m in re.finditer(r'#include\s+<collabtext/([^>]+)>|#include\s+"collabtext/([^"]+)"', p.read_text()):
            stack.append(m.group(1) or m.group(2))
print('\n'.join(sorted(out)))
PY
}

classify() {
    for header in "$@"; do
        local d
        d=$(deps "$header")
        if grep -lqE '#include <Q' $inc/*.h 2>/dev/null &&
           echo "$d" | grep -qE 'CollabDocument|PresenceManager|SyncManager'; then
            echo "qt   $header"
        else
            echo "core $header"
        fi
    done
}

echo "Advertised public headers, by half:"
classify "$inc"/*.h | sed 's|^|  |'

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp"
for header in "$inc"/*.h; do
    name=$(basename "$header")
    fn=${name//./_}; fn=${fn//-/_}
    cat > "$tmp/only_$fn.cpp" <<TU
/// Generated by A02a's public-header independence check.
///
/// This translation unit includes exactly one public header, as the first and
/// only library include, and is compiled against the public include tree alone.
/// A header that reaches into \`crdt/\` or \`src/\` -- or that quietly depends on
/// Qt in a Core consumer -- fails here rather than in somebody else's build.
///
/// Do not hand-edit. \`tools/check-public-headers.sh\` regenerates this directory.

#include <collabtext/$name>

int collabtext_public_header_$fn() { return 0; }
TU
done

# Compare only the generated sources; the comparison scratch file lives in the
# same directory and would otherwise report itself as drift.
if ! diff -ru --exclude=drift.txt "$out" "$tmp" > "$tmp/drift.txt" 2>&1; then
    echo
    echo "Drift between tests/public-headers and the current public tree:"
    cat "$tmp/drift.txt"
    exit 1
fi
echo
echo "tests/public-headers is in sync with include/collabtext."
